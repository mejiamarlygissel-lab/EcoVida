package com.ecovida.ecovida.model;


// Enum que define los diferentes tipos de residuos
// que pueden ser registrados en el sistema EcoVida.
public enum TipoResiduo {


    // Residuo compuesto principalmente
    // por material de papel.
    Papel,


    // Residuo compuesto principalmente
    // por cartón.
    Cartón,


    // Residuo compuesto principalmente
    // por material plástico.
    Plastico,


    // Residuo compuesto principalmente
    // por vidrio.
    Vidrio,


    // Residuo compuesto principalmente
    // por materiales metálicos.
    Metal
}
    

